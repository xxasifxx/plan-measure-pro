#!/usr/bin/env node
/**
 * extract-build-history.mjs  —  Phase A
 *
 * Read-only mining of `git log` producing docs/build-history.json with ONE
 * record per commit. NO top-down WBS assignment — activities are discovered
 * bottom-up in Phase B (scripts/discover-work-items.mjs).
 *
 * Per commit we capture:
 *   - sha, iso, date
 *   - kind: 'build' (file deltas), 'acceptance' (merge), 'bootstrap' (pre-work plan stub)
 *   - subject (full first line)
 *   - subjectTokens: lowercased meaningful tokens, stop-words stripped
 *   - files: [{ path, status, insertions, deletions }]  (from --numstat + --name-status)
 *   - pathTags: deterministic labels derived from paths (see TAG_RULES below)
 *
 * If any non-ignored path fails to tag, the script throws so the tag table
 * stays exhaustive. No "unclassified" silent fallback.
 */

import { execSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const REPO_ROOT = resolve(new URL('..', import.meta.url).pathname);
const OUT_PATH = resolve(REPO_ROOT, 'docs/build-history.json');

// ---------------------------------------------------------------------------
// Files we deliberately ignore: lockfiles, generated, planning, IDE config,
// and the Supabase-generated client/types (regenerated by tooling, not work).
const IGNORE_FILE = (f) =>
  /^(\.env|bun\.lockb?|package(-lock)?\.json|\.lovable\/|\.gitignore|README\.md|components\.json|eslint\.config\.|postcss\.config\.|tailwind\.config\.|tsconfig|vite\.config\.|vitest\.config\.|src\/integrations\/supabase\/(client|types)\.ts|docs\/)/.test(
    f,
  );

const TEMPLATE_SUBJECT_RE = /^template:/i;
const BOOTSTRAP_SUBJECT_RE = /^(Update plan|Save plan in Lovable|Changes)$/i;

// ---------------------------------------------------------------------------
// Path → tag rules. First match wins per rule; ALL matching rules contribute
// tags (a file can carry multiple tags, e.g. a page may also tag a feature).
// Tag namespaces:
//   page:<lower>            src/pages/<Name>.tsx
//   route:<group>           coarse grouping of pages
//   ui:<area>:<name>        src/components/<area>/<Name>.tsx (schedule, mobile, …)
//   component:<name>        src/components/<Name>.tsx (top-level)
//   shadcn                  src/components/ui/* (vendored primitives)
//   hook:<name>             src/hooks/<name>
//   lib:<area>:<name>       src/lib/<area>/<name>
//   lib:<name>              src/lib/<name>.ts (top-level)
//   test:<name>             src/test/<name>.test.ts
//   migration               supabase/migrations/*
//   edge:<name>             supabase/functions/<name>/*
//   supabase:config         supabase/config.toml | seed.sql
//   public:<kind>           public/* (sw, manifest, icons, sitemap, robots, llms, assets)
//   asset                   src/assets/*
//   native:capacitor        capacitor.config.ts
//   html                    index.html
//   styles                  src/index.css | src/App.css
//   app-shell               src/App.tsx | src/main.tsx | src/vite-env.d.ts | src/types/*
//   scripts:<name>          scripts/*
//   docs:native             docs/NATIVE_SETUP.md | docs/STORE_LISTING.md (not ignored — real work)
// ---------------------------------------------------------------------------

function tagPath(f) {
  const tags = [];
  let m;

  // Pages
  if ((m = f.match(/^src\/pages\/([A-Za-z0-9_]+)\.tsx$/))) {
    const name = m[1].toLowerCase();
    tags.push(`page:${name}`);
    // Coarse route groupings
    if (/^(landing|fajarpitch|mcfapitch|demo|p6xmldemo|xerdemo)$/.test(name)) tags.push('route:marketing');
    else if (/^(auth|resetpassword)$/.test(name)) tags.push('route:auth');
    else if (/^(admin|settings)$/.test(name)) tags.push('route:admin');
    else if (/^(rereview|dailyreport)$/.test(name)) tags.push('route:re');
    else if (/^(p6export)$/.test(name)) tags.push('route:schedule-export');
    else if (/^(projectcontrols)$/.test(name)) tags.push('route:schedule');
    else if (/^(documents|dashboard|index|notfound)$/.test(name)) tags.push('route:takeoff');
    return tags;
  }

  // Schedule UI subfolder
  if ((m = f.match(/^src\/components\/schedule\/([A-Za-z0-9_]+)\.tsx$/))) {
    tags.push(`ui:schedule:${m[1]}`);
    return tags;
  }

  // shadcn primitives
  if (/^src\/components\/ui\//.test(f)) {
    tags.push('shadcn');
    return tags;
  }

  // Top-level components
  if ((m = f.match(/^src\/components\/([A-Za-z0-9_]+)\.tsx$/))) {
    tags.push(`component:${m[1]}`);
    return tags;
  }

  // Hooks
  if ((m = f.match(/^src\/hooks\/([A-Za-z0-9-_]+)\.(tsx?|ts)$/))) {
    tags.push(`hook:${m[1]}`);
    return tags;
  }

  // src/lib subfolders
  if ((m = f.match(/^src\/lib\/([a-z0-9-]+)\/([A-Za-z0-9-_]+)\.ts$/))) {
    tags.push(`lib:${m[1]}:${m[2]}`);
    return tags;
  }

  // src/lib top-level files
  if ((m = f.match(/^src\/lib\/([A-Za-z0-9-_]+)\.ts$/))) {
    tags.push(`lib:${m[1]}`);
    return tags;
  }

  // Tests
  if ((m = f.match(/^src\/test\/([A-Za-z0-9-_]+)\.test\.ts$/))) {
    tags.push(`test:${m[1]}`);
    return tags;
  }
  if (f === 'src/test/setup.ts') {
    tags.push('test:setup');
    return tags;
  }

  // Supabase
  if (/^supabase\/migrations\//.test(f)) {
    tags.push('migration');
    return tags;
  }
  if ((m = f.match(/^supabase\/functions\/([A-Za-z0-9-_]+)\//))) {
    tags.push(`edge:${m[1]}`);
    return tags;
  }
  if (/^supabase\/(config\.toml|seed\.sql)$/.test(f)) {
    tags.push('supabase:config');
    return tags;
  }

  // Public assets
  if (/^public\/sw\./.test(f)) { tags.push('public:sw'); return tags; }
  if (/^public\/manifest/.test(f)) { tags.push('public:manifest'); return tags; }
  if (/^public\/(sitemap|robots|llms)/.test(f)) { tags.push('public:seo'); return tags; }
  if (/^public\/(favicon|apple-touch-icon|pwa-\d+)/.test(f)) { tags.push('public:icons'); return tags; }
  if (/^public\/fajar\//.test(f)) { tags.push('public:fajar-mockups'); return tags; }
  if (/^public\//.test(f)) { tags.push('public:misc'); return tags; }

  // src assets
  if (/^src\/assets\//.test(f)) { tags.push('asset'); return tags; }

  // App shell / styles / root config
  if (f === 'src/App.tsx' || f === 'src/main.tsx') { tags.push('app-shell'); return tags; }
  if (f === 'src/index.css' || f === 'src/App.css') { tags.push('styles'); return tags; }
  if (f === 'src/vite-env.d.ts' || /^src\/types\//.test(f)) { tags.push('app-shell'); return tags; }

  // Capacitor / native config
  if (f === 'capacitor.config.ts') { tags.push('native:capacitor'); return tags; }

  // index.html
  if (f === 'index.html') { tags.push('html'); return tags; }

  // Scripts
  if ((m = f.match(/^scripts\/([A-Za-z0-9-_.]+)\.(mjs|ts|js)$/))) {
    tags.push(`scripts:${m[1]}`);
    return tags;
  }

  // Native docs (real authored content, not generated)
  if (/^docs\/(NATIVE_SETUP|STORE_LISTING)\.md$/.test(f)) {
    tags.push('docs:native');
    return tags;
  }

  return tags; // empty → caller treats as error
}

// ---------------------------------------------------------------------------
const STOPWORDS = new Set([
  'a','an','the','and','or','of','to','for','in','on','with','from','by','at',
  'add','adds','added','update','updates','updated','use','using','make','makes','made',
  'fix','fixes','fixed','remove','removes','removed','set','sets','create','creates','created',
  'change','changes','changed','allow','allows','enable','enables','disable','disables',
  'is','be','that','this','it','its','as','via','into','out','up','down','off',
  'when','then','also','more','some','any','all','new','old',
  'feat','chore','refactor','wip',
]);

function tokenizeSubject(s) {
  return s
    .toLowerCase()
    .replace(/[`'"()[\],.:;!?]/g, ' ')
    .split(/[\s/_-]+/)
    .filter((t) => t.length >= 3 && !STOPWORDS.has(t) && !/^\d+$/.test(t));
}

// ---------------------------------------------------------------------------
function sh(cmd) {
  return execSync(cmd, { cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
}

function parseHeader(header) {
  const p1 = header.indexOf('|');
  const p2 = header.indexOf('|', p1 + 1);
  const p3 = header.indexOf('|', p2 + 1);
  return {
    hash: header.slice(0, p1),
    iso: header.slice(p1 + 1, p2),
    parents: header.slice(p2 + 1, p3),
    subject: header.slice(p3 + 1).trim(),
  };
}

function loadAllCommits() {
  // Two passes:
  //   1) --no-merges + --numstat → build commits with file deltas.
  //   2) --merges only → acceptance markers (the user accepting an iteration).
  // Merges in Lovable carry no diff vs first parent (preview was already at
  // that tree), so they don't contribute file work — they mark wall-clock
  // acceptance, which is what we want them to represent in the schedule.
  const buildRaw = sh(
    "git log --reverse --no-merges --numstat --format='__C__%H|%aI|%P|%s'",
  );
  const mergeRaw = sh(
    "git log --reverse --merges --format='__C__%H|%aI|%P|%s'",
  );

  const commits = [];

  for (const block of buildRaw.split('__C__')) {
    if (!block.trim()) continue;
    const [header, ...rest] = block.split('\n');
    const { hash, iso, subject } = parseHeader(header);
    if (TEMPLATE_SUBJECT_RE.test(subject)) continue;

    const files = [];
    for (const ln of rest) {
      const t = ln.trim();
      if (!t) continue;
      const parts = t.split('\t');
      if (parts.length < 3) continue;
      const [insRaw, delRaw, ...pathParts] = parts;
      const path = pathParts.join('\t');
      if (IGNORE_FILE(path)) continue;
      files.push({
        path,
        insertions: insRaw === '-' ? null : Number(insRaw),
        deletions: delRaw === '-' ? null : Number(delRaw),
      });
    }

    const kind =
      BOOTSTRAP_SUBJECT_RE.test(subject) && files.length === 0
        ? 'bootstrap'
        : 'build';

    commits.push({
      sha: hash,
      iso,
      date: iso.slice(0, 10),
      kind,
      subject,
      subjectTokens: tokenizeSubject(subject),
      files,
    });
  }

  for (const block of mergeRaw.split('__C__')) {
    if (!block.trim()) continue;
    const [header] = block.split('\n');
    const { hash, iso, subject } = parseHeader(header);
    if (TEMPLATE_SUBJECT_RE.test(subject)) continue;
    commits.push({
      sha: hash,
      iso,
      date: iso.slice(0, 10),
      kind: 'acceptance',
      subject,
      subjectTokens: tokenizeSubject(subject),
      files: [],
    });
  }

  commits.sort((a, b) => a.iso.localeCompare(b.iso));
  return commits;
}

// ---------------------------------------------------------------------------
function main() {
  const commits = loadAllCommits();
  if (commits.length === 0) throw new Error('No commits found');

  // Tag every file in every commit. Any untagged non-ignored file is a bug.
  const untaggedSamples = new Map();
  let untaggedCount = 0;
  for (const c of commits) {
    for (const f of c.files) {
      const tags = tagPath(f.path);
      if (tags.length === 0) {
        untaggedCount++;
        if (!untaggedSamples.has(f.path)) untaggedSamples.set(f.path, c.sha);
        f.tags = [];
      } else {
        f.tags = tags;
      }
    }
    // Roll up commit-level pathTags as union of file tags.
    const set = new Set();
    for (const f of c.files) for (const t of f.tags) set.add(t);
    c.pathTags = [...set].sort();
  }

  if (untaggedCount > 0) {
    console.error(`\n${untaggedCount} file occurrences had no tag — extend tagPath():`);
    for (const [path, sha] of [...untaggedSamples.entries()].slice(0, 30)) {
      console.error(`  ${path}   (first seen in ${sha.slice(0, 8)})`);
    }
    throw new Error('Untagged paths present; refusing to write.');
  }

  // Project-level summary.
  const buildCommits = commits.filter((c) => c.kind === 'build');
  const acceptCommits = commits.filter((c) => c.kind === 'acceptance');
  const bootstrapCommits = commits.filter((c) => c.kind === 'bootstrap');
  const start = commits[0].date;
  const end = commits[commits.length - 1].date;

  // Tag inventory: how many commits touch each tag.
  const tagCounts = new Map();
  for (const c of commits) {
    if (c.kind !== 'build') continue;
    for (const t of c.pathTags) tagCounts.set(t, (tagCounts.get(t) || 0) + 1);
  }
  const tagInventory = [...tagCounts.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([tag, commitCount]) => ({ tag, commitCount }));

  const out = {
    generatedAt: new Date().toISOString(),
    project: {
      start,
      end,
      lifespanDays:
        Math.round((new Date(end) - new Date(start)) / 86400000) + 1,
      totalCommits: commits.length,
      buildCommits: buildCommits.length,
      acceptanceCommits: acceptCommits.length,
      bootstrapCommits: bootstrapCommits.length,
    },
    tagInventory,
    commits,
  };

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, JSON.stringify(out, null, 2));
  console.log(`Wrote ${OUT_PATH}`);
  console.log(
    `  ${commits.length} commits ` +
      `(${buildCommits.length} build, ${acceptCommits.length} acceptance, ${bootstrapCommits.length} bootstrap)`,
  );
  console.log(`  ${tagInventory.length} distinct path tags`);
  console.log(`  Project span: ${start} → ${end} (${out.project.lifespanDays} days)`);
  console.log(`  Top tags:`);
  for (const t of tagInventory.slice(0, 12)) {
    console.log(`    ${String(t.commitCount).padStart(4)}  ${t.tag}`);
  }
}

main();
